/* =========================
   DOM ELEMENTS
========================= */

const productsContainer =
    document.querySelector(".products");

const categoryButtons =
    document.querySelectorAll(".categories button");


/* =========================
   CREATE PRODUCT CARD
========================= */

function createProductCard(product) {

    const card =
        document.createElement("article");

    card.className = "product-card";


    card.innerHTML = `

        <div class="product-image">

            <img
                src="${product.image}"
                alt="${product.name}"
            >

        </div>


        <div class="product-info">

            <span>
                ${product.english}
            </span>

            <h2>
                ${product.name}
            </h2>

           <div class="product-prices">

    <div class="price-option">

        <span>SMALL</span>

        <strong>
            ${product.smallPrice}
            <small>EGP</small>
        </strong>

    </div>


    <div class="price-option">

        <span>LARGE</span>

        <strong>
            ${product.price}
            <small>EGP</small>
        </strong>

    </div>

</div>

        </div>

    `;
card.addEventListener("click", () => {
    openProductModal(product);
});

    return card;
}


/* =========================
   DISPLAY PRODUCTS
========================= */

function displayProducts(category = "الكل") {

    if (!productsContainer) return;


    productsContainer.innerHTML = "";


    const filteredProducts =
        category === "الكل"
            ? products
            : products.filter(
                product =>
                    product.category === category
            );


    filteredProducts.forEach(product => {

        productsContainer.appendChild(
            createProductCard(product)
        );

    });

}


/* =========================
   CATEGORY FILTER
========================= */

categoryButtons.forEach(button => {

    button.addEventListener("click", () => {

        categoryButtons.forEach(btn => {
            btn.classList.remove("active");
        });


        button.classList.add("active");


        const category =
            button.textContent.trim();


        displayProducts(category);

    });

});


/* =========================
   INITIAL LOAD
========================= */

displayProducts("الكل");
/* =========================
   PRODUCT DETAILS MODAL
========================= */

const productModal =
    document.getElementById("productModal");

const modalClose =
    document.getElementById("modalClose");

const modalOverlay =
    document.querySelector(".modal-overlay");

const modalImage =
    document.getElementById("modalProductImage");

const modalEnglish =
    document.getElementById("modalProductEnglish");

const modalName =
    document.getElementById("modalProductName");

const modalDescription =
    document.getElementById("modalProductDescription");

const modalSmallPrice =
    document.getElementById("modalSmallPrice");

const modalLargePrice =
    document.getElementById("modalLargePrice");


/* =========================
   OPEN MODAL
========================= */

function openProductModal(product) {

    if (!productModal) return;

    modalImage.src =
        product.image;

    modalImage.alt =
        product.name;

    modalEnglish.textContent =
        product.english;

    modalName.textContent =
        product.name;

    modalDescription.textContent =
        `اختيار مميز من حمدي آيس لمحبي ${product.name}، بطعم غني وقوام كريمي معمول عشان يخلي كل لحظة أحلى.`;

    modalSmallPrice.textContent =
        product.smallPrice;

    modalLargePrice.textContent =
        product.price;

    productModal.classList.add("active");

    document.body.style.overflow = "hidden";
}


/* =========================
   CLOSE MODAL
========================= */

function closeProductModal() {

    if (!productModal) return;

    productModal.classList.remove("active");

    document.body.style.overflow = "";
}


modalClose?.addEventListener(
    "click",
    closeProductModal
);

modalOverlay?.addEventListener(
    "click",
    closeProductModal
);


/* ESC KEY */

document.addEventListener(
    "keydown",
    (event) => {

        if (
            event.key === "Escape" &&
            productModal?.classList.contains("active")
        ) {

            closeProductModal();

        }

    }
);
